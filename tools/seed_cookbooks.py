def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def arr(items):
    """A Postgres text[] literal. Ingredient ids are minted in SQL rather than
    written out here, which keeps the seed a third of the size and readable."""
    return 'array[' + ','.join(q(i) for i in items) + ']'


def book_sql(idx, slug, name, blurb, recipes):
    fid = uuid.uuid5(NS, 'folder:' + slug)
    out = [f"-- {name}: {len(recipes)} recipes",
           'insert into "CozyCookBookSchema".folders '
           '(id, name, blurb, user_id, is_public, position) values',
           f"  ('{fid}', {q(name)}, {q(blurb)}, null, true, {idx * 1024})",
           'on conflict (id) do update set name = excluded.name, blurb = excluded.blurb;',
           '',
           'insert into "CozyCookBookSchema".recipes',
           '  (id, title, ingredients, steps, folder_id, user_id, meal, is_public, position)',
           'select r.id, r.title,',
           "  (select coalesce(jsonb_agg(jsonb_build_object("
           "'id', gen_random_uuid(), 'name', n, 'isChecked', false) order by o), '[]'::jsonb)",
           '   from unnest(r.ing) with ordinality as t(n, o)),',
           "  (select coalesce(jsonb_agg(jsonb_build_object("
           "'id', gen_random_uuid(), 'text', st, 'isChecked', false) order by o), '[]'::jsonb)",
           '   from unnest(r.steps) with ordinality as t(st, o)),',
           f"  '{fid}', null, r.meal, true, r.pos",
           'from (values']
    rows = []
    for i, rec in enumerate(recipes):
        rid = uuid.uuid5(NS, f'recipe:{slug}:{rec["title"]}')
        rows.append(f"  ('{rid}'::uuid, {q(rec['title'])}, {arr(rec['ing'])}, "
                    f"{arr(rec['steps'])}, {q(rec['meal'])}, {i * 1024})")
    out.append(',\n'.join(rows))
    out.append(') as r(id, title, ing, steps, meal, pos)')
    out.append('on conflict (id) do update set title = excluded.title, '
               'ingredients = excluded.ingredients, steps = excluded.steps, '
               'meal = excluded.meal;')
    return '\n'.join(out)


def main():
    import os
    os.makedirs('supabase/cookbooks', exist_ok=True)
    total = 0
    for idx, (slug, name, blurb, recipes) in enumerate(BOOKS):
        sql = ('-- Starter cookbook, readable by every signed-in user, owned by nobody.\n'
               '-- Generated by tools/seed_cookbooks.py - do not hand-edit.\n\n'
               + book_sql(idx, slug, name, blurb, recipes) + '\n')
        path = f'supabase/cookbooks/{idx+1:02d}_{slug}.sql'
        open(path, 'w').write(sql)
        mix = {}
        for rec in recipes:
            mix[rec['meal']] = mix.get(rec['meal'], 0) + 1
        print(f'{path}  {len(recipes):>2} recipes  {len(sql):>6} bytes  {mix}')
        total += len(recipes)
    print(f'total: {total} recipes across {len(BOOKS)} cookbooks')


if __name__ == '__main__':
    main()
