"""seed_cookbooks.py — emit SQL for the starter cookbooks every user can read.

    python3 tools/seed_cookbooks.py > supabase/starter_cookbooks.sql

Six cookbooks, owned by nobody (user_id NULL, is_public true), so they appear
for anyone the first time they open CozyCookBook and cannot be edited or
deleted by anyone — the owner policies compare auth.uid() = user_id, which
never matches NULL.

Recipe ids are derived from the cookbook slug and recipe slug via uuid v5, so
re-running produces the same ids and the insert is idempotent. Ingredient names
are written the way the recipe reader wants them — quantity first, then the
food — because that is what the nutrition matcher in cozyhealth.js parses.
"""

